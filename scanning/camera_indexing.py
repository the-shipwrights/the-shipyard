import platform
import subprocess
import glob
import json
import plistlib
import cv2
import numpy as np

IR_KEYWORDS = ["ir", "infrared", "hello", "depth", "face", "biometric"]

def test_frame_is_ir(index, backend):
    """
    Captures a single frame to inspect color variance across R, G, and B channels.
    True IR feeds output grayscale or R ~= G ~= B data.
    """
    cap = cv2.VideoCapture(index, backend)
    if not cap.isOpened():
        return False

    ret, frame = cap.read()
    cap.release()

    if not ret or frame is None:
        return False

    # If it's a 1-channel image or uncompressed raw single-plane, it's IR/monochrome
    if len(frame.shape) == 2 or (len(frame.shape) == 3 and frame.shape[2] == 1):
        return True

    # Check color channel difference on 3-channel BGR frames
    if len(frame.shape) == 3 and frame.shape[2] == 3:
        b, g, r = frame[:, :, 0], frame[:, :, 1], frame[:, :, 2]
        # Calculate mean absolute delta between channels
        diff_rg = np.mean(np.abs(r.astype(int) - g.astype(int)))
        diff_gb = np.mean(np.abs(g.astype(int) - b.astype(int)))

        # Color webcams typically show deltas > 5-10 under regular light
        if (diff_rg + diff_gb) < 4.0:
            return True

    return False

def get_cameras_windows():
    """Queries Windows camera devices via PowerShell WMI/PnP and checks IR status."""
    cameras = []
    ps_cmd = (
        'Get-PnpDevice -Class "Camera", "Image" '
        '| Where-Object { $_.Status -eq "OK" } '
        '| Select-Object -Property FriendlyName, InstanceId '
        '| ConvertTo-Json'
    )
    try:
        res = subprocess.run(["powershell", "-NoProfile", "-Command", ps_cmd],
                             capture_output=True, text=True, check=True)
        data = json.loads(res.stdout) if res.stdout.strip() else []
        if isinstance(data, dict):
            data = [data]

        for idx, item in enumerate(data):
            name = item.get("FriendlyName", f"Camera {idx}")
            inst_id = item.get("InstanceId", "").lower()

            # 1. Metadata heuristic
            is_ir = any(kw in name.lower() for kw in IR_KEYWORDS) or any(kw in inst_id for kw in IR_KEYWORDS)

            # 2. Frame-level verification if metadata was inconclusive
            if not is_ir:
                is_ir = test_frame_is_ir(idx, cv2.CAP_DSHOW)

            cameras.append({
                "index": idx,
                "name": name,
                "is_ir": is_ir
            })
    except Exception:
        cameras = fallback_opencv_probe(cv2.CAP_DSHOW)
    return cameras

def get_cameras_linux():
    """Queries Linux cameras using /dev/v4l and v4l2-ctl capability checks."""
    cameras = []
    video_nodes = sorted(glob.glob('/dev/video*'))

    by_id_map = {}
    for link in glob.glob('/dev/v4l/by-id/*'):
        try:
            target = subprocess.run(['readlink', '-f', link],
                                    capture_output=True, text=True).stdout.strip()
            by_id_map[target] = link.split('/')[-1]
        except Exception:
            pass

    for node in video_nodes:
        name = by_id_map.get(node, node)

        # Check node capabilities via v4l2-ctl
        formats_info = ""
        try:
            out = subprocess.run(['v4l2-ctl', '--device=' + node, '--all'],
                                 capture_output=True, text=True).stdout
            if "Video Capture" not in out:
                continue  # Skip metadata pins
            for line in out.splitlines():
                if "Card type" in line:
                    name = line.split(":", 1)[1].strip()
                    break

            # Check supported pixel formats
            fmt_out = subprocess.run(['v4l2-ctl', '--device=' + node, '--list-formats'],
                                     capture_output=True, text=True).stdout
            formats_info = fmt_out.lower()
        except FileNotFoundError:
            pass

        try:
            node_idx = int(node.replace('/dev/video', ''))
        except ValueError:
            node_idx = len(cameras)

        # IR detection heuristic:
        # Check node name/id or V4L2 pixel format (e.g., GREY, Y10, Y16, INVI)
        is_ir = (
            any(kw in name.lower() for kw in IR_KEYWORDS) or
            any(fmt in formats_info for fmt in ['y10 ', 'y16 ', 'grey', 'z16', 'invi'])
        )

        if not is_ir:
            is_ir = test_frame_is_ir(node_idx, cv2.CAP_V4L2)

        cameras.append({
            "index": node_idx,
            "name": name,
            "path": node,
            "is_ir": is_ir
        })
    return cameras

def get_cameras_macos():
    """Queries macOS cameras via system_profiler."""
    cameras = []
    try:
        res = subprocess.run(["system_profiler", "-xml", "SPCameraDataType"],
                             capture_output=True, check=True)
        plist_data = plistlib.loads(res.stdout)
        raw_cams = plist_data[0].get('_items', []) if plist_data else []

        for idx, item in enumerate(raw_cams):
            name = item.get('_name', 'Camera')
            unique_id = item.get('spcamera_unique-id', '').lower()

            is_ir = any(kw in name.lower() for kw in IR_KEYWORDS) or any(kw in unique_id for kw in IR_KEYWORDS)
            if not is_ir:
                is_ir = test_frame_is_ir(idx, cv2.CAP_AVFOUNDATION)

            cameras.append({
                "index": idx,
                "name": name,
                "is_ir": is_ir
            })
    except Exception:
        cameras = fallback_opencv_probe(cv2.CAP_AVFOUNDATION)
    return cameras

def fallback_opencv_probe(backend, max_tested=6):
    """Fallback index probe that reads sample frames to classify devices."""
    found = []
    for idx in range(max_tested):
        cap = cv2.VideoCapture(idx, backend)
        if cap.isOpened():
            is_ir = test_frame_is_ir(idx, backend)
            found.append({
                "index": idx,
                "name": f"Camera Index {idx}",
                "is_ir": is_ir
            })
            cap.release()
    return found

def get_system_cameras():
    os_name = platform.system()
    if os_name == "Windows":
        return get_cameras_windows()
    elif os_name == "Linux":
        return get_cameras_linux()
    elif os_name == "Darwin":
        return get_cameras_macos()
    else:
        return fallback_opencv_probe(cv2.CAP_ANY)

